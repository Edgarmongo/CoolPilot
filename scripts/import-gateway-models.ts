import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

/**
 * Regenerates the model-gateway snapshot used by 系统 / 模型管理.
 *
 * Usage:
 *   tsx scripts/import-gateway-models.ts <payload.json> [--source=<label>] [--date=<yyyy-mm-dd>]
 *
 * <payload.json> is the raw JSON body of the gateway model list request, either
 * `{"data":["model-a","model-b"]}` or a bare `["model-a","model-b"]` array.
 * It contains public model ids only - never pass a payload that includes
 * cookies, tokens or account data.
 */
const args = process.argv.slice(2);
const inputPath = args.find((arg) => !arg.startsWith("--"));

/** Local calendar date (yyyy-mm-dd) of the machine that ran the import. */
function localDate(now = new Date()) {
  return new Date(now.getTime() - now.getTimezoneOffset() * 60_000).toISOString().slice(0, 10);
}
const sourceArg = args.find((arg) => arg.startsWith("--source="))?.slice("--source=".length);
const dateArg = args.find((arg) => arg.startsWith("--date="))?.slice("--date=".length);

if (!inputPath) {
  console.error("Usage: tsx scripts/import-gateway-models.ts <payload.json> [--source=<label>] [--date=<yyyy-mm-dd>]");
  process.exit(1);
}

const rawPayload = readFileSync(path.resolve(inputPath), "utf8").replace(/^\uFEFF/, "");
const payload = JSON.parse(rawPayload) as unknown;
const rawModels = Array.isArray(payload)
  ? payload
  : Array.isArray((payload as { data?: unknown[] }).data)
    ? (payload as { data: unknown[] }).data
    : [];

const models = Array.from(
  new Set(
    rawModels
      .map((entry) => (typeof entry === "string" ? entry.trim() : ""))
      .filter(Boolean),
  ),
);

if (models.length === 0) {
  throw new Error(`No model ids found in ${inputPath}`);
}

const source = sourceArg?.trim() || "model gateway";
const capturedAt = dateArg?.trim() || localDate();
const target = path.join(process.cwd(), "src", "features", "ai-settings", "model-gateway-snapshot.ts");

const lines = [
  "/**",
  " * Generated by scripts/import-gateway-models.ts - do not edit by hand.",
  " *",
  ` * Source: ${source}`,
  ` * Captured: ${capturedAt}`,
  ` * Models: ${models.length}`,
  " */",
  `export const modelGatewaySnapshotSource = ${JSON.stringify(source)};`,
  `export const modelGatewaySnapshotCapturedAt = ${JSON.stringify(capturedAt)};`,
  "export const modelGatewayModels: readonly string[] = [",
  ...models.map((model) => `  ${JSON.stringify(model)},`),
  "];",
  "",
];

writeFileSync(target, lines.join("\n"), "utf8");
console.log(JSON.stringify({ ok: true, target, source, capturedAt, models: models.length }, null, 2));
